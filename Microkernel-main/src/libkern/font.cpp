    uint8_t Font::GetRow(char Character, int Row) const {

        if(Row < 0 || Row >= this->Height) {

            return 0;

        };

        if(Character >= 'a' && Character <= 'z') {

            Character -= 'a' - 'A';

        };

        for(const auto& Glyph : Glyphs) {

            if(Glyph.Character == Character) {

                return Glyph.Rows[Row];

            };

        };

        return this->GetRow('?', Row);

    };

